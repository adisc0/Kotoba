import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";
import { transform as javascript } from "esbuild";
import { transform as stylesheet } from "lightningcss";

const root = path.dirname(fileURLToPath(import.meta.url));
const read = (file) => fs.readFile(path.join(root, file), "utf8");
const datasets = {
  BASE_WORDS: "words",
  YUMA_LESSONS: "lessons",
  VERB_FORMS: "forms",
  GRAMMAR_SEGMENTS: "grammar",
};
let code = "";
for (const [constant, name] of Object.entries(datasets)) {
  const data = JSON.parse(await read(`src/data/${name}.json`));
  code += `const ${constant}=${JSON.stringify(data)};\n`;
}
for (const file of ["app", "kana", "numbers-time"])
  code += (await read(`src/${file}.js`)) + "\n";
const js = (
  await javascript(code, {
    minify: true,
    charset: "utf8",
    target: "es2020",
    format: "iife",
    legalComments: "none",
  })
).code;
const css = stylesheet({
  filename: "styles.css",
  code: Buffer.from(await read("src/styles.css")),
  minify: true,
}).code;
const hash = (value) =>
  createHash("sha256").update(value).digest("hex").slice(0, 10);
const jsName = `reference.${hash(js)}.js`,
  cssName = `reference.${hash(css)}.css`;
const html = (await read("src/index.html"))
  .replace(
    "<!-- STYLES -->",
    `<link rel="stylesheet" href="./assets/${cssName}">`,
  )
  .replace(
    "<!-- SCRIPTS -->",
    `<script src="./assets/${jsName}" defer></script>`,
  );
// Keep the familiar index.html usable directly, plus a clean Pages upload folder.
for (const directory of [root, path.join(root, "dist")]) {
  const assets = path.join(directory, "assets");
  await fs.mkdir(assets, { recursive: true });
  // Only prune files generated by this build; user/reference files are never touched.
  for (const name of await fs.readdir(assets))
    if (/^reference\.[a-f0-9]{10}\.(js|css)$/.test(name))
      await fs.unlink(path.join(assets, name));
  await fs.writeFile(path.join(assets, jsName), js);
  await fs.writeFile(path.join(assets, cssName), css);
  await fs.writeFile(path.join(directory, "index.html"), html);
  await fs.writeFile(path.join(directory, ".nojekyll"), "");
}
console.log(
  `Built static reference: ${Buffer.byteLength(html)} B HTML, ${Buffer.byteLength(js)} B JS, ${css.length} B CSS.`,
);
