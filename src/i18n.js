const originalText = new WeakMap(),
  originalAttributes = new WeakMap();
const studyGlosses =
  ".card-english,.card-context-jp,.card-context-romaji,.word-meaning,.lv-meaning,.study-example-en p,.sentence-translation p,.verb-form-meaning,.verb-form-example p,.sentence-part .gloss";
function translatedUI(text) {
  const key = text.replace(/\s+/g, " ").trim();
  if (UI_JA[key]) return UI_JA[key];
  return key
    .replace(/^(\d+) of (\d+) entries$/, "$2語中$1語を表示")
    .replace(/^(\d+) words & expressions$/, "$1のことばと表現")
    .replace(/^(\d+) words and expressions$/, "$1のことばと表現")
    .replace(/^(\d+) words?$/, "$1語")
    .replace(/\bHiragana\b/g, "ひらがな")
    .replace(/\bKatakana\b/g, "カタカナ")
    .replace(/At a glance/g, "一覧表")
    .replace(/46 basic characters/g, "基本の46文字")
    .replace(/Voiced & P sounds/g, "濁音と半濁音")
    .replace(/Combination sounds/g, "拗音")
    .replace(/\bLESSON (\d+)/g, "レッスン $1")
    .replace(/\bLesson (\d+)/g, "レッスン $1")
    .replace(/\bTRIAL\b/g, "体験")
    .replace(/\bTrial\b/g, "体験")
    .replace(/(\d+) words · (\d+) sentences/g, "$1語 · 例文$2つ")
    .replace(/^Listen to (.+)$/, "$1を聞く");
}
function translateNode(node) {
  if (node.nodeType === Node.TEXT_NODE) {
    if (
      !node.parentElement ||
      node.parentElement.closest(
        "script,style,#languageToggle,svg,[data-no-translate]," + studyGlosses,
      )
    )
      return;
    const current = node.nodeValue,
      record = originalText.get(node);
    let english = record && current === record.last ? record.en : current;
    if (!english.trim()) return;
    const output =
      interfaceLanguage === "ja"
        ? english.trim() === "Dictionary" &&
          node.parentElement.closest(".verb-form-label")
          ? "辞書形"
          : translatedUI(english)
        : english;
    if (current !== output) node.nodeValue = output;
    originalText.set(node, { en: english, last: output });
    return;
  }
  if (node.nodeType !== Node.ELEMENT_NODE) return;
  if (node.matches("script,style,#languageToggle,[data-no-translate]")) return;
  let attrs = originalAttributes.get(node);
  if (!attrs) {
    attrs = {};
    originalAttributes.set(node, attrs);
  }
  for (const name of [
    "aria-label",
    "title",
    "placeholder",
    "data-mobile-label",
  ])
    if (node.hasAttribute(name)) {
      const current = node.getAttribute(name),
        old = attrs[name],
        english = old && current === old.last ? old.en : current;
      const output =
        interfaceLanguage === "ja" ? translatedUI(english) : english;
      if (current !== output) node.setAttribute(name, output);
      attrs[name] = { en: english, last: output };
    }
  [...node.childNodes].forEach(translateNode);
}
const languageObserver = new MutationObserver((records) => {
  languageObserver.disconnect();
  const roots = new Set();
  for (const r of records) {
    if (r.type === "characterData") roots.add(r.target);
    else for (const n of r.addedNodes) roots.add(n);
  }
  for (const node of roots) if (node.isConnected) translateNode(node);
  languageObserver.observe(document.body, {
    childList: true,
    subtree: true,
    characterData: true,
  });
});
function applyInterfaceLanguage() {
  languageObserver.disconnect();
  translateNode(document.body);
  document.documentElement.lang = interfaceLanguage;
  el("languageToggle").textContent =
    interfaceLanguage === "ja" ? "EN" : "日本語";
  el("languageToggle").setAttribute(
    "aria-label",
    interfaceLanguage === "ja"
      ? "Switch interface to English"
      : "表示を日本語に切り替える",
  );
  el("languageToggle").setAttribute(
    "aria-pressed",
    String(interfaceLanguage === "ja"),
  );
  document.title =
    interfaceLanguage === "ja"
      ? "ことば帳 | アルケンの日本語ガイド"
      : "Kotoba | Alken's Notebook";
  languageObserver.observe(document.body, {
    childList: true,
    subtree: true,
    characterData: true,
  });
}
let languageAnimationTimer;
el("languageToggle").addEventListener("click", () => {
  clearTimeout(languageAnimationTimer);
  const animate = !window.matchMedia("(prefers-reduced-motion: reduce)")
    .matches;
  document.body.classList.toggle("language-changing", animate);
  interfaceLanguage = interfaceLanguage === "en" ? "ja" : "en";
  try {
    localStorage.setItem("kotoba-interface-language", interfaceLanguage);
  } catch {}
  applyInterfaceLanguage();
  if (animate) {
    languageAnimationTimer = setTimeout(() => {
      document.body.classList.remove("language-changing");
    }, 700);
  }
});
applyInterfaceLanguage();
